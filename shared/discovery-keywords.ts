export function customKeywords(value: string) {
  return [
    ...new Set(
      value
        .split(/[,;\n]+/)
        .map((term) => term.trim())
        .filter(Boolean),
    ),
  ].slice(0, 100);
}
export function searchKeywords(config: DiscoverySettings, industry: string) {
  const custom = customKeywords(config.keywords);
  const builtIn =
    config.keyword_library !== false
      ? (keywordLibrary[industry] ?? keywordLibrary.Other)
      : [];
  return [...new Set([...custom, ...builtIn])].length
    ? [...new Set([...custom, ...builtIn])]
    : [industry.replaceAll("&", " ") || "independent retail"];
}
